#!/usr/bin/env python3
"""Generated CTH ledger changelog view — QBP#817, beekeeper-added requirement
(2026-11-16, "add the changelog view", on top of the converged variant-A spec).

Renders every merged change in merge order, one row per change: derived
version, merge time, issue, PR, note, touched anchor ids. Built only from git
history plus archive/cth-inventory/changes.d/ fragments (scripts/ledger_version.
py) — never from anything a PR authored directly, so it is readable without
running anything and regenerates byte-identically (the `ledger-reproduces`
CI check, QBP#817 item 3's sibling for this file). No PR may hand-edit it; the
PR lint (scripts/ledger_bookkeeping_lint.py) treats it the same as the ledger's
frozen fields and the inverse-anchor audit snapshot.

Acceptance check (beekeeper, QBP#817): after two PRs merge, this view shows two
new consecutive derived versions (e.g. 6.25.0, 6.26.0) in merge order, with
their issue/PR links, and neither merged PR's own diff touched this file.

Usage:
    python3 scripts/generate_ledger_changelog_view.py              # write
    python3 scripts/generate_ledger_changelog_view.py --check       # verify, exit 1 on drift
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ledger_version import LEDGER, fragment_versions, frozen_base_version

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_MD = REPO_ROOT / "analysis/cth-ledger-changelog.md"

HEADER = """# CTH ledger changelog (generated)

**Generated by:** `scripts/generate_ledger_changelog_view.py` — do not hand-edit; a PR
that edits this file directly fails `scripts/ledger_bookkeeping_lint.py`.

The ledger's stored `version`/`changelog[]`/`last_updated` are frozen (QBP#817,
variant A, beekeeper-ruled 2026-11-16) — a content PR never authors them. This
table is the current, derived state: one row per merged change, built only from
git history plus `archive/cth-inventory/changes.d/` fragments. The frozen base
is `{base}`.

| Version | Merged | Issue | PR | Note | Touched anchor ids |
|---|---|---|---|---|---|
"""


def render(ledger_path: Path = LEDGER) -> str:
    # archive/cth-inventory/<ledger>.json -> changes.d is its sibling,
    # repo root is three parents up. Derived from ledger_path (not a hardcoded
    # module constant) so this also works against a throwaway test repo.
    ledger_path = Path(ledger_path)
    changes_dir = ledger_path.parent / "changes.d"
    repo_root = ledger_path.parents[2]
    base = frozen_base_version(ledger_path)
    rows = fragment_versions(ledger_path, changes_dir, repo_root)
    lines = [HEADER.format(base=base)]
    for row in rows:
        d = row["data"]
        note = d["note"].replace("|", "\\|").replace("\n", " ")
        ids = ", ".join(f"`{i}`" for i in d["touched_ids"])
        lines.append(
            f"| `{row['derived_version']}` | {row['merge_time']} | "
            f"[#{d['issue']}](https://github.com/JamesPagetButler/QBP/issues/{d['issue']}) | "
            f"[#{d['pr']}](https://github.com/JamesPagetButler/QBP/pull/{d['pr']}) | "
            f"{note} | {ids} |\n"
        )
    if not rows:
        lines.append("| _(no merged fragments yet)_ | | | | | |\n")
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ledger", default=str(LEDGER))
    ap.add_argument("--out", default=str(OUT_MD))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    out_path = Path(args.out)
    rendered = render(Path(args.ledger))

    if args.check:
        current = out_path.read_text(encoding="utf-8") if out_path.exists() else None
        if current != rendered:
            print(
                f"DRIFT: {out_path} does not match a fresh regeneration — "
                f"re-run `python3 scripts/generate_ledger_changelog_view.py` and commit the result."
            )
            sys.exit(1)
        print(f"OK: {out_path} matches a fresh regeneration.")
        return

    out_path.write_text(rendered, encoding="utf-8")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
