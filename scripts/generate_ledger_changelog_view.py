#!/usr/bin/env python3
"""Generated CTH ledger changelog view — QBP#817, beekeeper-added requirement
(2026-11-16, "add the changelog view", on top of the converged variant-A spec).

Renders every merged change in merge order, one row per change: derived
version, merge time, issue, PR, note, touched anchor ids. Built only from git
history plus archive/cth-inventory/changes.d/ fragments (scripts/ledger_version.
py) — never from anything a PR authored directly.

**This view is NEVER committed to the repo** (D1, qbp-oppenheimer, QBP#817
PR-1 review, 2026-11-17). A committed copy would have to be regenerated and
re-committed by every later content PR just to keep a `--check`-style drift
check green — which reintroduces the exact bookkeeping collision this whole
design removes, just moved from the ledger into this file, and a squash merge
would leave its `Merged` column stale the moment the next unrelated PR runs
`--check` against it. `scripts/ledger_bookkeeping_lint.py` instead forbids
this file from ever appearing in a content PR's diff at all — see
`FORBIDDEN_PATHS` there. The durable, "readable without running anything"
copy (the beekeeper's requirement) is published by a POST-MERGE job on
`push: branches: [master]` — see `.github/workflows/ledger-bookkeeping-
frozen.yml`'s `publish-ledger-changelog-view` job, which writes this render
to the GitHub Actions job summary of that push (`$GITHUB_STEP_SUMMARY`), not
to a tracked file.

Acceptance check (beekeeper, QBP#817, restated base-relative per qbp-
architecture's D5/seq5162 since the frozen base is whatever's live when PR-1
merges, never a literal number): after two PRs merge, a fresh render shows
two new consecutive derived versions (base+1, base+2) in true merge order
(D2), with their issue/PR links, and NEITHER merged PR's own diff touched
this file, `archive/cth-inventory/changes.d/`'s existing fragments, or the
ledger's frozen fields.

Usage:
    python3 scripts/generate_ledger_changelog_view.py                 # print to stdout
    python3 scripts/generate_ledger_changelog_view.py --step-summary   # append to $GITHUB_STEP_SUMMARY
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

from ledger_version import LEDGER, fragment_versions, frozen_base_version

REPO_ROOT = Path(__file__).resolve().parent.parent

HEADER = """# CTH ledger changelog

**Generated by:** `scripts/generate_ledger_changelog_view.py`, post-merge, on every
push to master. This render is never committed — see that script's module docstring
(D1, QBP#817) for why.

The ledger's stored `version`/`changelog[]`/`last_updated` are frozen (QBP#817,
variant A, beekeeper-ruled 2026-11-16) — a content PR never authors them. This
table is the current, derived state: one row per merged change, built only from
git history plus `archive/cth-inventory/changes.d/` fragments. The frozen base
is `{base}`.

| Version | Merged | Issue | PR | Note | Touched anchor ids |
|---|---|---|---|---|---|
"""


def render(ledger_path: Path = LEDGER) -> str:
    # archive/cth-inventory/<ledger>.json -> changes.d is its sibling,
    # repo root is three parents up. Derived from ledger_path (not a hardcoded
    # module constant) so this also works against a throwaway test repo.
    ledger_path = Path(ledger_path)
    changes_dir = ledger_path.parent / "changes.d"
    repo_root = ledger_path.parents[2]
    base = frozen_base_version(ledger_path)
    rows = fragment_versions(ledger_path, changes_dir, repo_root)
    lines = [HEADER.format(base=base)]
    for row in rows:
        d = row["data"]
        note = d["note"].replace("|", "\\|").replace("\n", " ")
        ids = ", ".join(f"`{i}`" for i in d["touched_ids"])
        lines.append(
            f"| `{row['derived_version']}` | {row['merge_time']} | "
            f"[#{d['issue']}](https://github.com/JamesPagetButler/QBP/issues/{d['issue']}) | "
            f"[#{d['pr']}](https://github.com/JamesPagetButler/QBP/pull/{d['pr']}) | "
            f"{note} | {ids} |\n"
        )
    if not rows:
        lines.append("| _(no merged fragments yet)_ | | | | | |\n")
    return "".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ledger", default=str(LEDGER))
    ap.add_argument(
        "--step-summary",
        action="store_true",
        help="append the render to $GITHUB_STEP_SUMMARY instead of printing to stdout "
        "(the post-merge publish step; fails loudly if the env var isn't set, so a "
        "misconfigured workflow doesn't silently publish nothing)",
    )
    args = ap.parse_args()

    rendered = render(Path(args.ledger))

    if args.step_summary:
        summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
        if not summary_path:
            raise SystemExit(
                "--step-summary requires $GITHUB_STEP_SUMMARY (set by GitHub Actions); "
                "not present in this environment"
            )
        with open(summary_path, "a", encoding="utf-8") as f:
            f.write(rendered)
        print(f"appended to {summary_path}")
        return

    print(rendered, end="")


if __name__ == "__main__":
    main()
