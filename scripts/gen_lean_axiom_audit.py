#!/usr/bin/env python3
"""Generate the Lean axiom-audit driver files — QBP issue #827 AC2/AC3.

COVERAGE COMES FROM LEAN, NOT FROM PYTHON. Python only decides which MODULES are in scope —
the transitive import closure of the `@[default_target]` roots in `proofs/lakefile.lean`,
i.e. exactly what CI's bare `lake build` compiles (parsed with `check_layer_imports.py`'s
lakefile/import helpers). For each default-target root it writes one driver file that
imports that root and runs a Lean metaprogram over the ELABORATED ENVIRONMENT: every
constant whose defining module is in scope — theorem, def, instance, axiom, inductive,
auxiliary lemma, however the source is written (comments, strings, `#print axioms` or
not) — has its axiom closure computed, and any axiom outside
{propext, Classical.choice, Quot.sound} is reported. One driver per root because roots can
clash when imported together (e.g. two `lean_exe` roots each defining `main`).

usage:
  gen_lean_axiom_audit.py --proofs proofs --out-dir DIR      write DIR/AxiomAudit_<n>.lean + DIR/manifest.json
  gen_lean_axiom_audit.py --proofs proofs --topo             print the in-scope modules in build order
  gen_lean_axiom_audit.py --proofs proofs --modules M1 M2 --out-dir DIR
                                                             (fixtures/tests) audit exactly these modules
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_layer_imports import (
    imports_of,
    lakefile_targets,
    resolve_module,
)  # noqa: E402

AUDIT_MARK = "AXIOM-AUDIT-827"

TEMPLATE = """\
/- Generated by scripts/gen_lean_axiom_audit.py (QBP #827) — do not edit, do not commit. -/
{imports}
import Lean

open Lean Elab Command

/-- Axiom closure of every constant reachable from `roots`, memoised (iterative DFS, so no
deep recursion). Mirrors `Lean.collectAxioms`: an axiom contributes itself; definitions,
theorems and opaques contribute type + value; inductives add their constructors. -/
def qbpAuditAxiomsOf (env : Environment) (roots : Array Name) : Std.HashMap Name NameSet := Id.run do
  let mut memo : Std.HashMap Name NameSet := {{}}
  let mut onStack : NameSet := {{}}
  for r in roots do
    if memo.contains r then continue
    let mut stack : Array (Name × Bool) := #[(r, false)]
    while 0 < stack.size do
      let (n, expanded) := stack.back!
      stack := stack.pop
      if memo.contains n then continue
      let some ci := env.find? n | memo := memo.insert n {{}}; continue
      let mut deps : Array Name := ci.type.getUsedConstants
      match ci with
      | .defnInfo v => deps := deps ++ v.value.getUsedConstants
      | .thmInfo v => deps := deps ++ v.value.getUsedConstants
      | .opaqueInfo v => deps := deps ++ v.value.getUsedConstants
      | .inductInfo v => deps := deps ++ v.ctors.toArray
      | _ => pure ()
      if !expanded then
        onStack := onStack.insert n
        stack := stack.push (n, true)
        for d in deps do
          if !memo.contains d && !onStack.contains d then
            stack := stack.push (d, false)
      else
        let mut acc : NameSet := {{}}
        if ci matches .axiomInfo _ then acc := acc.insert n
        for d in deps do
          if let some s := memo.get? d then
            for a in s do acc := acc.insert a
        memo := memo.insert n acc
        onStack := onStack.erase n
  return memo

run_cmd do
  let env ← getEnv
  let targets : Array Name := #[{targets}]
  let std : NameSet := ({{}} : NameSet).insert ``propext |>.insert ``Classical.choice |>.insert ``Quot.sound
  let modNames := env.header.moduleNames
  let mut idxs : Std.HashSet Nat := {{}}
  for t in targets do
    match modNames.findIdx? (· == t) with
    | some i => idxs := idxs.insert i
    | none => logError m!"{mark} MISSING-MODULE {{t}}"
  let mut inScope : Array Name := #[]
  for (n, _) in env.constants.map₁ do
    if let some i := env.getModuleIdxFor? n then
      if idxs.contains i.toNat then inScope := inScope.push n
  let memo := qbpAuditAxiomsOf env inScope
  let mut bad : Nat := 0
  for n in inScope do
    let axs := (memo.get? n).getD {{}}
    let extra := axs.toList.filter (fun a => !std.contains a)
    unless extra.isEmpty do
      bad := bad + 1
      let some i := env.getModuleIdxFor? n | continue
      logError m!"{mark} NONSTD {{n}} module={{modNames[i.toNat]!}} axioms={{extra}}"
  logInfo m!"{mark} SUMMARY root={root} modules={{idxs.size}}/{{targets.size}} declarations={{inScope.size}} bad={{bad}}"
"""


def scope(proofs: Path) -> tuple[list[str], dict[str, list[str]], list[str]]:
    """(default roots, closure per root in build order, srcdirs)."""
    errors: list[str] = []
    targets = lakefile_targets(proofs, errors)
    if errors:
        raise SystemExit("; ".join(errors))
    srcdirs = ["."] + sorted({sd for sd, _, _ in targets if sd != "."})
    roots = [r for _, rs, d in targets if d for r in rs]
    closures: dict[str, list[str]] = {}
    for root in roots:
        order: list[str] = []
        seen: set[str] = set()

        def visit(mod: str) -> None:  # post-order = build order
            if mod in seen:
                return
            seen.add(mod)
            p = resolve_module(mod, proofs, srcdirs)
            if p is None:
                return  # external (Mathlib, Init, …)
            for dep in imports_of(p):
                visit(dep)
            order.append(mod)

        sys.setrecursionlimit(10000)
        visit(root)
        closures[root] = order
    return roots, closures, srcdirs


def all_modules(proofs: Path, srcdirs: list[str]) -> list[str]:
    out = set()
    for p in proofs.rglob("*.lean"):
        rel = p.relative_to(proofs)
        if ".lake" in rel.parts or rel.name == "lakefile.lean":
            continue
        for sd in sorted(srcdirs, key=len, reverse=True):
            base = proofs / sd
            try:
                r = p.relative_to(base)
            except ValueError:
                continue
            if sd == "." and any(rel.parts[0] == s for s in srcdirs if s != "."):
                continue
            out.add(".".join(r.with_suffix("").parts))
            break
    return sorted(out)


def write(out: Path, groups: list[tuple[str, list[str]]], extra: dict) -> None:
    out.mkdir(parents=True, exist_ok=True)
    files = []
    for k, (root, mods) in enumerate(groups):
        imports = "\n".join(f"import {m}" for m in ([root] if root else mods))
        text = TEMPLATE.format(
            imports=imports,
            targets=", ".join(f"`{m}" for m in mods),
            mark=AUDIT_MARK,
            root=root or "(explicit)",
        )
        f = out / f"AxiomAudit_{k}.lean"
        f.write_text(text, encoding="utf-8")
        line = text.splitlines().index("run_cmd do") + 1
        files.append(
            {"file": str(f), "root": root, "modules": mods, "run_cmd_line": line}
        )
    (out / "manifest.json").write_text(
        json.dumps({"drivers": files, **extra}, indent=1) + "\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--proofs", default="proofs")
    ap.add_argument("--out-dir")
    ap.add_argument("--topo", action="store_true")
    ap.add_argument("--modules", nargs="*")
    a = ap.parse_args()
    proofs = Path(a.proofs)
    if a.modules:
        write(
            Path(a.out_dir), [("", a.modules)], {"in_scope": a.modules, "not_built": []}
        )
        return 0
    roots, closures, srcdirs = scope(proofs)
    in_scope: list[str] = []
    for r in roots:
        for m in closures[r]:
            if m not in in_scope:
                in_scope.append(m)
    if a.topo:
        print("\n".join(in_scope))
        return 0
    not_built = [m for m in all_modules(proofs, srcdirs) if m not in in_scope]
    write(
        Path(a.out_dir),
        [(r, closures[r]) for r in roots],
        {"in_scope": in_scope, "not_built": not_built},
    )
    print(
        f"axiom-audit drivers: {len(roots)} root(s), {len(in_scope)} in-scope module(s); "
        f"{len(not_built)} module(s) in proofs/ not built by `lake build`: {', '.join(not_built) or '—'}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
