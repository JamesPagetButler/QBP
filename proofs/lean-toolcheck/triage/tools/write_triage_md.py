import re
import json, sys, collections

tri = json.load(open(sys.argv[1]))
ml = json.load(open(sys.argv[2]))
out = sys.argv[3]
L = []
L.append(
    "# Candidate triage, next upgrade — Lean v4.30.0 → v4.36.0 (DRAFT, no bump done)"
)
L.append("")
L.append(
    "**Status:** draft template for #723 (issue #823 W5, R5). Generated 2026-11-20 from the release notes"
)
L.append(
    "in `leanprover/reference-manual` `Manual/Releases/v4_3{1..6}_*.lean` (read as text; the GitHub release bodies"
)
L.append(
    "only link there) and the Mathlib `v4.35.0` source tarball (read as text, `56a0058`). Nothing downloaded was"
)
L.append(
    "executed. Summary, method and the top items are in [`../FEATURES.md`](../FEATURES.md) §Candidate triage."
)
L.append("")
L.append(
    "**Dispositions:** `breaking` = breaking AND touches QBP usage → test or migration note · `breaking-no-touch` = breaking"
)
L.append(
    "for its feature, QBP does not use the named API · `relevant` = QBP uses the feature → covered by a named tool test"
)
L.append("and/or the full project rebuild (G1) · `not-relevant` = one-line reason.")
L.append("")
c = collections.Counter(x["disp"] for x in tri)
L.append("| Disposition | Items |")
L.append("|---|---|")
for k in ["breaking", "breaking-no-touch", "relevant", "not-relevant"]:
    L.append(f"| {k} | {c[k]} |")
L.append(f"| **total** | **{len(tri)}** |")
L.append("")
L.append("## Lean release-note items")
L.append("")
order = {"breaking": 0, "breaking-no-touch": 1, "relevant": 2, "not-relevant": 3}
for ver in sorted(
    {x["ver"] for x in tri}, key=lambda v: [int(p) for p in v[1:].split(".")]
):
    rows = [x for x in tri if x["ver"] == ver]
    L.append(f"### {ver} ({len(rows)} items)")
    L.append("")
    L.append("| PR | Section | Disposition | Item (truncated) | Reason |")
    L.append("|---|---|---|---|---|")
    for x in sorted(rows, key=lambda x: (order[x["disp"]], x["sec"], x["pr"])):
        t = (
            re.sub(r"https?://[^\s)]*", "‹url›", x["text"])
            .replace("|", "\\|")
            .replace("\n", " ")
        )
        if len(t) > 140:
            t = t[:137] + "…"
        r = x["reason"].replace("|", "\\|")
        L.append(f"| lean4#{x['pr']} | {x['sec']} | {x['disp']} | {t} | {r} |")
    L.append("")
L.append("## Mathlib v4.30.0 (`c5ea003`) → v4.35.0 (`56a0058`): what hits QBP's usage")
L.append("")
L.append(
    "Method: every Mathlib module QBP imports, and every identifier QBP's comment-stripped `.lean` files mention"
)
L.append(
    "(qualified, or unqualified under the file's `open` namespaces), was looked up in a text index of `theorem|lemma|def|`"
)
L.append(
    "`abbrev|instance|alias|structure|class|inductive` declarations of both trees (namespace-tracked), plus their"
)
L.append(
    "`@[deprecated …]` attributes and `deprecated_module` shims. Limits: names generated by `@[to_additive]`/`irreducible_def`"
)
L.append(
    "are invisible to the text index (so `zsmulRec`, `nhds` show as false 'missing'; both verified present by hand); simp-set"
)
L.append(
    "*contents* and instance changes cannot be found this way — the rebuild (G1) is the test for those."
)
L.append("")
L.append(
    f"Index sizes: {ml['stats']['old_decl_lastnames']} / {ml['stats']['new_decl_lastnames']} declaration short-names; "
    f"{ml['stats']['old_deprecations']} → {ml['stats']['new_deprecations']} `@[deprecated]` declarations; "
    f"{ml['stats']['old_deprecated_modules']} → {ml['stats']['new_deprecated_modules']} deprecated modules."
)
L.append("")
L.append(
    "| Kind | Mathlib name / module | Since | Replacement | QBP users | Disposition |"
)
L.append("|---|---|---|---|---|---|")
repl = {
    "Mathlib.Data.Real.Basic": "Mathlib.Basic.Real.Basic",
    "Mathlib.Data.Complex.Basic": "Mathlib.Basic.Complex.Basic",
    "Mathlib.Data.Real.Sign": "Mathlib.Basic.Real.Sign",
}
for i in ml["imports"]:
    if i["deprecated_new"] or not i["new"]:
        L.append(
            f"| deprecated module | `{i['module']}` | {i['deprecated_new'][0] if i['deprecated_new'] else '—'} | `{repl.get(i['module'], '?')}` | "
            f"{', '.join('`'+u+'`' for u in i['used_by'])} | breaking (warning, not error): change the import on the bump branch; T00 + the suite's own T04–T07/T09/T13/T15/T16 import it too |"
        )
for h in ml["newly_deprecated_used"]:
    L.append(
        f"| deprecated lemma | `{h['mathlib_name']}` | {h['since']} | `Set.mem_ofPred_eq` (`setOf` → `Set.ofPred`) | "
        f"{', '.join('`'+u+'`' for u in h['used_by'])} (3 `simp only` sites) | breaking (warning): rename on the bump branch |"
    )
for h in ml["missing_at_new"]:
    L.append(
        f"| index 'missing' | `{h['token']}` | — | — | {', '.join('`'+u+'`' for u in h['used_by'])} | not-relevant: false positive "
        f"(`{h['token']}` is generated by `{'@[to_additive]' if h['token']=='zsmulRec' else 'irreducible_def'}`; present at v4.35.0 by grep) |"
    )
L.append(
    "| deprecated tactic syntax | `peel`, `whatsnew`, `countHeartbeats`, `deprecate to`, `to_additive_ignore_args` | 2026-08/09 | per message | none (grep 0) | not-relevant |"
)
L.append(
    "| tactic modules | `Mathlib.Tactic.{Module,FieldSimp,Linarith,NormNum,Ring,Positivity,LinearCombination,Abel,FinCases}` | — | — | present at v4.35.0 | not-relevant (unchanged paths) |"
)
L.append("")
open(out, "w").write("\n".join(L) + "\n")
print(len(L), "lines")
